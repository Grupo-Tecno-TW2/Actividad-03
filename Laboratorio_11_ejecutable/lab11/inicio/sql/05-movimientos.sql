SET NAMES utf8mb4;

CREATE TABLE ventas (
    id         INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    fecha      DATETIME NOT NULL,
    cliente    VARCHAR(80) NOT NULL,
    usuario_id INT UNSIGNED NOT NULL,
    total      DECIMAL(12, 2) NOT NULL,
    CONSTRAINT fk_ventas_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id),
    INDEX ix_ventas_fecha (fecha)                        -- los reportes filtran por fecha
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci;

CREATE TABLE venta_detalle (
    venta_id        INT UNSIGNED NOT NULL,
    producto_id     INT UNSIGNED NOT NULL,
    cantidad        INT NOT NULL,
    precio_unitario DECIMAL(10, 2) NOT NULL,             -- el precio DE ESE DÍA (el producto puede cambiar de precio)
    PRIMARY KEY (venta_id, producto_id),
    CONSTRAINT chk_detalle_cantidad CHECK (cantidad > 0),
    CONSTRAINT fk_detalle_venta FOREIGN KEY (venta_id) REFERENCES ventas (id) ON DELETE CASCADE,
    CONSTRAINT fk_detalle_producto FOREIGN KEY (producto_id) REFERENCES productos (id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci;

CREATE TABLE acopios (
    id            INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    fecha         DATETIME NOT NULL,
    socio_id      INT UNSIGNED NOT NULL,
    producto_id   INT UNSIGNED NOT NULL,
    cantidad      INT NOT NULL,
    precio_pagado DECIMAL(10, 2) NOT NULL,               -- lo que la asociación paga al socio por unidad
    CONSTRAINT chk_acopio_cantidad CHECK (cantidad > 0),
    CONSTRAINT fk_acopio_socio FOREIGN KEY (socio_id) REFERENCES socios (id),
    CONSTRAINT fk_acopio_producto FOREIGN KEY (producto_id) REFERENCES productos (id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci;

